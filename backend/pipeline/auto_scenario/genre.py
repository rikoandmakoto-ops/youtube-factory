"""タイトル → ジャンル分類（レポート側と生成側で共有）。

もともと `run_daily_pdca.py` にだけ存在したキーワード表を、シナリオ生成側からも
参照できるよう切り出したもの。日次 PDCA レポートの「テーマ（ジャンル）別の成績」と、
チャンネル JSON の `genre_blacklist`（生成停止ジャンル）が**同じ分類器**を使うことで、
「レポートで平均0再生と判定されたジャンル名」をそのまま除外設定に書けるようにしている。

分類は「タイトルに含まれるキーワードの先勝ち」。表の並び順が優先度そのものなので、
広いキーワード（例: 体・音）を持つジャンルは下に置くこと。
"""

from __future__ import annotations

from typing import Dict, List, Tuple

OTHER_GENRE = "その他"

# ジャンル分類用キーワード（タイトルに含まれれば該当）。先に来たものを優先。
GENRE_KEYWORDS: Dict[str, List[Tuple[str, List[str]]]] = {
    "daily-science": [
        ("睡眠・夢", ["夢", "睡眠", "眠", "寝", "あくび"]),
        ("脳・記憶・心理", ["脳", "記憶", "心理", "錯覚", "意識", "感情", "ストレス", "緊張"]),
        ("体の不思議", ["体", "声", "骨", "痛", "くしゃみ", "しゃっくり", "耳", "目", "肌", "指", "お腹", "免疫", "涙"]),
        ("食・飲", ["食", "飲", "味", "コーヒー", "アイス", "風呂", "温", "熱"]),
        ("宇宙・天体", ["宇宙", "星", "星座", "地球", "月", "木星", "酸素", "重力"]),
        ("日常の違和感", ["水たまり", "信号", "電車", "スマホ", "冷蔵庫", "シャワー", "雨", "音"]),
    ],
    "scp-lab": [
        ("SCP個別オブジェクト", ["scp-", "scp‑", "scp ", "彫刻", "医師", "シャイ", "爬虫類", "ikea", "トースター"]),
        ("オブジェクトクラス", ["keter", "euclid", "safe", "thaumiel", "apollyon", "クラス"]),
        ("財団組織・職員", ["財団", "o5", "評議会", "機動部隊", "dクラス", "職員", "収容"]),
        ("対立組織・Kクラス", ["goc", "蛇の手", "カオス", "反乱", "kクラス", "xk", "終焉", "シナリオ"]),
        ("ミーム・認識災害", ["ミーム", "認識", "情報災害", "感染", "知るだけ"]),
    ],
}


def classify_genre(channel_id: str, title: str) -> str:
    """タイトルをチャンネル固有のジャンルへ分類する。該当なしは "その他"。"""
    t = (title or "").lower()
    for genre, kws in GENRE_KEYWORDS.get(channel_id, []):
        for kw in kws:
            if kw.lower() in t:
                return genre
    return OTHER_GENRE


def known_genres(channel_id: str) -> List[str]:
    """そのチャンネルで分類され得るジャンル名の一覧（設定値の綴り検証用）。"""
    return [g for g, _ in GENRE_KEYWORDS.get(channel_id, [])]
