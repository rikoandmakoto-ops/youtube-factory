"""ショート投稿タイトルの末尾マーカー付与を1箇所に集める。

背景（2026-09-07）:
    ショートの単体公開／ペア公開には「説明文ファイルにタイトル行が無ければ
    ジョブ名に `【ショート】` を足す」というフォールバックが4箇所ある
    (`api_phase3` 2箇所 / `api_phase4` 2箇所)。これが**無条件の文字列連結**
    だったため、ジョブ名の時点で既にマーカーが付いている回では

        なぜ〜なのか【ショート】【ショート】

    と二重に付いた投稿タイトルが出ていた。付与は必ずこの関数を通す。

`【ショート】` はタイトルのどこにあっても「もう付いている」とみなす。
`hashtag_optimizer` 側もこのマーカーを位置に関係なく剥がしているので、
末尾一致だけを見ると `〜【ショート】 #shorts` のような並びを取りこぼす。
"""

from __future__ import annotations

SHORT_SUFFIX = "【ショート】"


def with_short_suffix(title: str) -> str:
    """`title` に `【ショート】` を1つだけ付けて返す。

    既に含まれていればそのまま返す（二重付与の防止）。空文字なら
    マーカーだけの無意味なタイトルを作らず空文字のまま返し、
    呼び出し側の `or` フォールバックに続きを任せる。
    """
    base = (title or "").strip()
    if not base:
        return ""
    if SHORT_SUFFIX in base:
        return base
    return base + SHORT_SUFFIX
