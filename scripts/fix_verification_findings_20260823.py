RULES = {
    "scp-lab": lambda t: "—" not in t and re.search(r"[怖恐]", t) and "本当の理由" not in t,
    "yokai-watch": lambda t: "—" not in t and re.search(r"秘密|隠|本当|実は", t),
    "pokemon-lab": lambda t: "—" not in t and re.search(r"秘密|隠", t),
}
# 固有名（総称のみのタイトルを弾く）
GENERIC = {
    "pokemon-lab": re.compile(r"^(不思議な進化|ライバルたち|悪の組織|進化先の選択|ゲーム内ストーリー)"),
    "yokai-watch": re.compile(r"^(最強妖怪|人気キャラ)"),
}
FAKE_NUM = re.compile(r"(9つ|26部隊|4名|レベル4|13の)")


def main():
    problems = []

    # --- チャンネルコンフィグ ---
    for base in DIRS:
        for ch, style in STYLES.items():
            p = base / f"{ch}.json"
            if not p.exists():
                continue
            d = json.loads(p.read_text(encoding="utf-8"))
            tp = d.setdefault("theme_priority", {})
            changed = []
            if tp.get("title_style") != style:
                tp["title_style"] = style
                changed.append("title_style")
            if tp.get("good_examples") != GOOD_EXAMPLES[ch]:
                tp["good_examples"] = GOOD_EXAMPLES[ch]
                changed.append("good_examples")
            # daily-science: viral_hooks に残る「99%が知らない」を除去
            vh = tp.get("viral_hooks")
            if isinstance(vh, str) and "99%が知らない" in vh:
                tp["viral_hooks"] = re.sub(
                    r"[^。]*99%が知らない[^。]*。?", "", vh
                ).strip() + "（※2026-08-23: 希少性ワード『99%が知らない』は効果未確認のため除去）"
                changed.append("viral_hooks(99%除去)")
            elif isinstance(vh, list):
                nv = [x for x in vh if "99%が知らない" not in str(x)]
                if len(nv) != len(vh):
                    tp["viral_hooks"] = nv
                    changed.append("viral_hooks(99%除去)")
            # yokai-watch: line_chars から到達不能な total_chars_max を修正
            if ch == "yokai-watch":
                sf = d.get("short_format") or {}
                if sf.get("total_chars_max") == 330:
                    sf["total_chars_max"] = 310  # 7行×37字 + 8行目52字 = 311字が上限
                    changed.append("total_chars_max 330->310(到達可能な上限に修正)")
            if changed:
                shutil.copy2(p, p.with_suffix(f".json.{STAMP}"))
                p.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")
                print(f"{p.relative_to(ROOT)}: {', '.join(changed)}")

    # --- テーマキュー ---
    for ch, titles in QUEUE.items():
        qp = ROOT / "data" / "channels" / ch / "theme_queue.json"
        q = json.loads(qp.read_text(encoding="utf-8"))
        items = q.get("items", [])
        local = []
        for t in titles:
            if not RULES[ch](t):
                local.append(f"{ch}: ルール違反 {t}")
            if FAKE_NUM.search(t):
                local.append(f"{ch}: 捏造数字が残存 {t}")
            g = GENERIC.get(ch)
            if g and g.match(t):
                local.append(f"{ch}: 固有名なし {t}")
        if len(set(titles)) != len(titles):
            local.append(f"{ch}: キュー内重複あり")
        dup = set(titles) & set(GOOD_EXAMPLES.get(ch, []))
        if dup:
            local.append(f"{ch}: good_examplesと重複 {dup}")
        if local:
            problems.extend(local)
            continue
        shutil.copy2(qp, qp.with_suffix(f".json.{STAMP}"))
        for it, new in zip(items, titles):
            it["title"] = new
        # 本日追加分の created_at を実際の日付に修正
        for it in items:
            if it.get("source") == "orchestrator_pdca_20260823":
                it["created_at"] = NOW
        qp.write_text(json.dumps(q, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"{qp.relative_to(ROOT)}: {len(items)}件のタイトルを再修正")

    if problems:
        print("\n!! 未解消の問題:")
        for x in problems:
            print("   ", x)
    else:
        print("\n全チェック通過（ルール適合・捏造数字なし・固有名あり・重複なし）")


if __name__ == "__main__":
    main()
