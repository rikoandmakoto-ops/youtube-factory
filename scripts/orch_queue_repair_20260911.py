def main():
    # --- 全件を先に検証。1件でも落ちたら何も書かない ---
    problems = []
    for ch, mapping in REWRITES.items():
        cfg = json.load(open(os.path.join(ROOT, "data", "channels", f"{ch}.json"), encoding="utf-8"))
        for old, new in mapping.items():
            r = tc.check(new, cfg)
            if not r["ok"]:
                problems.append((ch, new, tc.violation_summary(r)))
    if problems:
        print("❌ 書き換え候補に違反あり。中止:")
        for ch, t, v in problems:
            print(f"   {ch}: {t} -> {v}")
        return 1
    total = sum(len(m) for m in REWRITES.values())
    print(f"✅ 書き換え候補 {total} 件すべて hard_constraints を通過")

    for ch, mapping in REWRITES.items():
        p = os.path.join(ROOT, "data", "channels", f"{ch}.json")
        b = f"{p}.bak_qrepair_{STAMP}"
        if not os.path.exists(b):
            shutil.copy2(p, b)
        cfg = json.load(open(p, encoding="utf-8"))
        q = cfg.get("autopilot", {}).get("theme_queue", [])
        n = 0
        for item in q:
            if isinstance(item, dict) and str(item.get("title")) in mapping:
                item["title_prev_20260911"] = item["title"]
                item["title"] = mapping[str(item["title"])]
                n += 1
        with open(p, "w", encoding="utf-8") as f:
            json.dump(cfg, f, ensure_ascii=False, indent=2)
            f.write("\n")
        ng = [i for i in q if isinstance(i, dict) and not tc.check(str(i.get("title", "")), cfg)["ok"]]
        print(f"  {ch:15} {n} 件書き換え → 残 NG {len(ng)}/{len(q)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
